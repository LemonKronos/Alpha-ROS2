
#!/usr/bin/env python3
"""Convert a FOAM sphere hierarchy into base_link-frame ROS 2 YAML."""

import argparse
import json
import math
import re
from pathlib import Path
from typing import Any


FOAM_DIR = Path(__file__).resolve().parent
CONFIG_DIR = FOAM_DIR.resolve().parent
DEFAULT_JSON = FOAM_DIR / "alpha-foam.json"
DEFAULT_POSE = FOAM_DIR / "alpha-foam-pose.txt"
DEFAULT_OUTPUT = CONFIG_DIR / "alpha-foam.yaml"
DEFAULT_DEPTH = 1
MESH_SCALE = 0.001  # DAE millimeters -> meters


def parse_pose(path: Path) -> tuple[float, ...]:
    """Parse an SDF <pose>x y z roll pitch yaw</pose>."""
    text = path.read_text(encoding="utf-8")
    match = re.search(r"<pose>\s*(.*?)\s*</pose>", text, re.DOTALL)

    if match is None:
        raise ValueError(f"No <pose>...</pose> element found in {path}")

    values = tuple(float(value) for value in match.group(1).split())
    if len(values) != 6:
        raise ValueError(f"Expected 6 pose values, got {len(values)}")

    return values


def rotation_matrix(
    roll: float, pitch: float, yaw: float
) -> tuple[tuple[float, ...], ...]:
    """Build the SDF fixed-axis roll-pitch-yaw rotation matrix."""
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)

    return (
        (cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr),
        (sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr),
        (-sp, cp * sr, cp * cr),
    )


def transform_sphere(
    sphere: dict[str, Any],
    rotation: tuple[tuple[float, ...], ...],
    translation: tuple[float, float, float],
    scale: float,
) -> tuple[float, float, float, float]:
    """Transform a sphere from mesh coordinates into base_link coordinates."""
    origin = sphere["origin"]
    if len(origin) != 3:
        raise ValueError("Sphere origin must contain exactly 3 values")

    x, y, z = (float(value) * scale for value in origin)

    transformed = tuple(
        translation[i]
        + sum(rotation[i][j] * (x, y, z)[j] for j in range(3))
        for i in range(3)
    )
    radius = float(sphere["radius"]) * abs(scale)

    if radius <= 0:
        raise ValueError("Sphere radius must be positive")

    return (*transformed, radius)


def load_spheres(path: Path, depth: int) -> list[dict[str, Any]]:
    """Select one level of the FOAM sphere hierarchy."""
    data = json.loads(path.read_text(encoding="utf-8"))

    if not isinstance(data, list) or not 0 <= depth < len(data):
        raise ValueError(f"Depth {depth} is not present in {path}")

    spheres = data[depth].get("spheres")
    if not isinstance(spheres, list) or not spheres:
        raise ValueError(f"No spheres found at depth {depth}")

    return spheres


def write_yaml(path: Path, spheres: list[tuple[float, ...]]) -> None:
    """Write a ROS 2 wildcard parameter file with a flat sphere array."""
    values = [value for sphere in spheres for value in sphere]

    lines = [
        "# Generated by transform_foam.py; do not edit manually.",
        "# Sphere order: x, y, z, radius; all values in meters.",
        "/**:",
        "  ros__parameters:",
        "    foam_spheres: [",
    ]

    for index in range(0, len(values), 4):
        group = values[index:index + 4]
        formatted = ", ".join(f"{value:.9f}" for value in group)
        comma = "," if index + 4 < len(values) else ""
        lines.append(f"      {formatted}{comma}")

    lines.extend(["    ]", ""])
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path, default=DEFAULT_JSON)
    parser.add_argument("--pose", type=Path, default=DEFAULT_POSE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--depth", type=int, default=DEFAULT_DEPTH)
    args = parser.parse_args()

    px, py, pz, roll, pitch, yaw = parse_pose(args.pose)
    rotation = rotation_matrix(roll, pitch, yaw)
    source_spheres = load_spheres(args.json, args.depth)

    result = [
        transform_sphere(
            sphere, rotation, (px, py, pz), MESH_SCALE
        )
        for sphere in source_spheres
    ]

    write_yaml(args.output, result)
    print(f"Converted {len(result)} spheres from depth {args.depth}.")
    print(f"Wrote: {args.output}")


if __name__ == "__main__":
    main()
